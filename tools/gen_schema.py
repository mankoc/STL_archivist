"""Generate ``rust/stl-core/src/storage/schema_sql.rs`` from the SQLAlchemy models.

The Rust migration (``storage::migrate``) must create exactly the schema that
``Base.metadata.create_all`` and ``db._ensure_columns`` create, down to the SQL
text SQLite keeps in ``sqlite_master``.  Rather than retyping that DDL, this
script compiles it from ``app/database/models.py`` with the SQLite dialect:

* per table, in dependency order: ``CREATE TABLE`` and the indexes ``create_all``
  adds with it;
* per column: the ``ALTER TABLE … ADD COLUMN`` statement ``_ensure_columns``
  would run if the column were missing.

Run it after changing ``models.py``::

    python tools/gen_schema.py           # rewrite the Rust file
    python tools/gen_schema.py --check   # exit 1 if it is out of date (used by tests)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import sqlite  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.database import db, vectors  # noqa: E402
from app.database.models import Base  # noqa: E402
from app.utils.image_embedding import EMBED_DIM, EMBED_MODEL_ID  # noqa: E402

OUT = ROOT / "rust" / "stl-core" / "src" / "storage" / "schema_sql.rs"
DIALECT = sqlite.dialect()


def _add_column_ddl(table, col) -> str:
    """The statement ``db._ensure_columns`` builds for a missing column."""
    col_type = col.type.compile(DIALECT)
    nullable = "" if col.nullable else " NOT NULL"
    if col.server_default is not None:
        default = f" DEFAULT {col.server_default.arg}"
    elif not col.nullable and col.default is not None:
        val = col.default.arg
        default = f" DEFAULT {int(val) if isinstance(val, bool) else repr(val)}"
    else:
        default = ""
    return f'ALTER TABLE "{table.name}" ADD COLUMN "{col.name}" {col_type}{nullable}{default}'


def _rust_str(s: str) -> str:
    """A Rust raw string literal for *s*."""
    hashes = "#"
    while f'"{hashes}' in s:
        hashes += "#"
    return f'r{hashes}"{s}"{hashes}'


def render() -> str:
    lines = [
        "//! Generated by `tools/gen_schema.py` from `app/database/models.py`. Do not edit.",
        "//!",
        "//! `TABLES`: in dependency order, each table's `CREATE TABLE` and the indexes",
        "//! `create_all` creates with it. `ADD_COLUMNS`: the `ALTER TABLE ... ADD COLUMN`",
        "//! that `db._ensure_columns` runs for a column missing from an existing table.",
        "",
        "pub struct TableDdl {",
        "    pub name: &'static str,",
        "    pub create: &'static str,",
        "    pub indexes: &'static [&'static str],",
        "}",
        "",
        "pub const TABLES: &[TableDdl] = &[",
    ]
    for table in Base.metadata.sorted_tables:
        create = str(CreateTable(table).compile(dialect=DIALECT))
        indexes = [str(CreateIndex(ix).compile(dialect=DIALECT))
                   for ix in sorted(table.indexes, key=lambda ix: ix.name)]
        lines.append("    TableDdl {")
        lines.append(f'        name: "{table.name}",')
        lines.append(f"        create: {_rust_str(create)},")
        lines.append("        indexes: &[")
        lines += [f"            {_rust_str(ix)}," for ix in indexes]
        lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    lines.append("")
    lines.append("/// `(table, column, ddl)`.")
    lines.append("pub const ADD_COLUMNS: &[(&str, &str, &str)] = &[")
    for table in Base.metadata.sorted_tables:
        for col in table.columns:
            lines.append(f'    ("{table.name}", "{col.name}", {_rust_str(_add_column_ddl(table, col))}),')
    lines.append("];")
    lines.append("")
    lines.append("/// `db.ENSURE_INDEXES`: indexes added to existing databases as well.")
    lines.append("pub const ENSURE_INDEXES: &[&str] = &[")
    lines += [f"    {_rust_str(ddl)}," for ddl in db.ENSURE_INDEXES]
    lines.append("];")
    lines.append("")
    lines.append("/// `db.MODELS_VIEW_SQL`, recreated on every start.")
    lines.append(f"pub const MODELS_VIEW: &str = {_rust_str(db.MODELS_VIEW_SQL)};")
    lines.append("")
    lines.append("/// `vectors`: the embedding model the stored vectors must come from.")
    lines.append(f"pub const EMBED_MODEL_ID: &str = {_rust_str(EMBED_MODEL_ID)};")
    lines.append(f"pub const EMBED_DIM: i64 = {EMBED_DIM};")
    lines.append(f"pub const VECTOR_TABLE: &str = {_rust_str(vectors.TABLE)};")
    lines.append(f"pub const VECTOR_INFO: &str = {_rust_str(vectors._INFO)};")
    lines.append(f"pub const VECTOR_INFO_CREATE: &str = {_rust_str(vectors._CREATE_INFO)};")
    lines.append(f"pub const VECTOR_TABLE_CREATE: &str = {_rust_str(vectors._CREATE_TABLE)};")
    lines.append("/// `vectors._CREATE_TRIGGER`: per connection, deletes a removed image's vector.")
    lines.append(f"pub const VECTOR_DELETE_TRIGGER: &str = {_rust_str(vectors._CREATE_TRIGGER)};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run python tools/gen_schema.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
